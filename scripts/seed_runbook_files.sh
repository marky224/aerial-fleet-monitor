#!/usr/bin/env bash
#
# Seed the runbook reference Files (ContentVersion) into the Salesforce org.
#
# Each runbooks/*.md becomes a ContentDocument whose Title matches the matching
# AFM_Runbook__mdt.Title__c. That Title is the join key AFM_CaseTriageService
# (Group B) uses to link the runbook File to a Case via ContentDocumentLink.
# PathOnClient is set to "<runbook-id>.md" for traceability back to the source.
#
# The Apex class AFM_RunbookFileSeeder does the work. This script calls it once,
# from anonymous Apex, with every runbook, so the seed is one transaction. For
# each runbook the class creates the File (no File has the title), adds a new
# version to the existing File (the content changed; Cases keep their links), or
# skips it (the content is unchanged). It never deletes a File and never touches
# a ContentDocumentLink, and an error leaves every File as it was. Safe to
# re-run. On a fresh org run `make sf-deploy` first: it deploys the class.
#
# Output: one RUNBOOK_FILE line per runbook (action, path, the File's Case-link
# count before and after, title) and one RUNBOOK_SEED summary line, then a
# read-only query table of the Files (title, path, version number, created date).
#
# Env:
#   AFM_FILES_SEED_DRY_RUN=1   print the anonymous Apex and exit; no org is called
#
# Usage:
#   scripts/seed_runbook_files.sh [target-org-alias]   # default: afm-dev
#
set -euo pipefail

ORG="${1:-${SF_TARGET_ORG:-afm-dev}}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUNBOOK_DIR="$REPO_ROOT/runbooks"

if [[ ! -d "$RUNBOOK_DIR" ]] || ! compgen -G "$RUNBOOK_DIR/*.md" > /dev/null; then
  echo "error: no runbook markdown found in $RUNBOOK_DIR" >&2
  exit 1
fi

APEX_FILE="$(mktemp --suffix=.apex)"
trap 'rm -f "$APEX_FILE"' EXIT

# --- Build the anonymous Apex: one AFM_RunbookFileSeeder.seed(...) call.
{
  echo "// Auto-generated by scripts/seed_runbook_files.sh — do not edit by hand."
  echo "AFM_RunbookFileSeeder.seed(new List<AFM_RunbookFileSeeder.RunbookFile>{"
} > "$APEX_FILE"

count=0
sep=""
for md in "$RUNBOOK_DIR"/*.md; do
  id="$(basename "$md" .md)"
  title="$(grep -m1 '^title:' "$md" | sed -E 's/^title:[[:space:]]*"?([^"]*)"?[[:space:]]*$/\1/')"
  if [[ -z "$title" ]]; then
    echo "error: no 'title:' frontmatter in $md" >&2
    exit 1
  fi
  esc_title="${title//\'/\\\'}"   # escape single quotes for the Apex string literal
  b64="$(base64 -w0 "$md")"
  count=$((count + 1))
  printf "%s    new AFM_RunbookFileSeeder.RunbookFile('%s', '%s.md', EncodingUtil.base64Decode('%s'))" \
    "$sep" "$esc_title" "$id" "$b64" >> "$APEX_FILE"
  sep=$',\n'
done
printf '\n});\n' >> "$APEX_FILE"

if [[ "${AFM_FILES_SEED_DRY_RUN:-}" == "1" ]]; then
  cat "$APEX_FILE"
  exit 0
fi

echo "Seeding ${count} runbook Files into org '${ORG}'..."
if ! run_out="$(sf apex run --target-org "$ORG" --file "$APEX_FILE" 2>&1)"; then
  echo "ERROR: the runbook File seed failed. It runs as one transaction, so nothing was written." >&2
  echo "  If the error is 'Invalid type: AFM_RunbookFileSeeder', run 'make sf-deploy' first." >&2
  printf '%s\n' "$run_out" | grep -v '^Execute Anonymous: ' >&2 || true
  exit 1
fi

# The class logs its report only after its insert succeeded. The CLI also echoes
# the anonymous Apex source line by line; leave that out.
report="$(printf '%s\n' "$run_out" | grep -v '^Execute Anonymous: ' | grep -oE 'RUNBOOK_(FILE|SEED) .*' || true)"
if [[ -n "$report" ]]; then
  printf '%s\n' "$report"
fi
file_lines="$(printf '%s\n' "$report" | grep -c '^RUNBOOK_FILE ' || true)"
seed_lines="$(printf '%s\n' "$report" | grep -c '^RUNBOOK_SEED ' || true)"
if [[ "$file_lines" -ne "$count" || "$seed_lines" -ne 1 ]]; then
  echo "ERROR: expected ${count} RUNBOOK_FILE lines and 1 RUNBOOK_SEED line from the seed, got ${file_lines} and ${seed_lines}." >&2
  echo "  The Apex run did not fail, so the Files may have been written; only its report is incomplete:" >&2
  printf '%s\n' "$run_out" | grep -v '^Execute Anonymous: ' >&2 || true
  exit 1
fi

# Read-back, independent of the report above: the runbook Files as triage finds
# them. A File that was not re-created keeps its created date, and its version
# number goes up by one for each new version.
sf data query --target-org "$ORG" --result-format human \
  --query "SELECT Title, PathOnClient, VersionNumber, ContentDocument.CreatedDate FROM ContentVersion WHERE IsLatest = true AND PathOnClient LIKE '%.md' ORDER BY Title"
echo "Done."
